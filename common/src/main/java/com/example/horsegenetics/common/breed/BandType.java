package com.example.horsegenetics.common.breed;

/**
 * The two shapes a wild horse herd spawns in.
 *
 * <ul>
 *   <li><b>{@link #TRADITIONAL}</b> - one stallion, his harem of mares, and
 *       their foals. 3-5 adults plus up to ~3 babies; the stallion is the herd
 *       lead.</li>
 *   <li><b>{@link #BACHELOR}</b> - a band of 3-5 stallions, no mares, no foals.
 *       The first one spawned is the lead.</li>
 * </ul>
 */
public enum BandType {
    TRADITIONAL,
    BACHELOR
}
