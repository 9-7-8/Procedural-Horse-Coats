#!/usr/bin/env node
// Writes the index of wiki/verification.html: one row per wiki page that
// carries a Verification tab, alphabetical, with that tab's own one-sentence
// summary.
//
//   node wiki/tools/bake-verification-index.mjs
//
// Nothing here is typed. A page is on this list BY HAVING A VERIFICATION TAB,
// the same way a gene is on the census by existing. The contract a page must
// keep, and which this tool enforces:
//
//   <section id="verification" class="tab-panel" data-tab="verification"
//            data-tab-label="Verification"
//            data-tab-hint="Built, not yet seen in a game">
//
//   <div class="note verify-summary">
//       <span class="label">What needs verifying here</span>
//       <p>One sentence saying what is built and unconfirmed.</p>
//   </div>
//
// The sentence is the row. The count beside it is the panel's own <li> tally,
// computed here rather than written down, so a checklist that shrinks says so
// without anybody editing this page.
//
// It HARD-FAILS rather than writing a wrong index, because a verification list
// that quietly omits a page is worse than no list: a panel with no summary box,
// a summary box outside a verification panel, two of either, or a page with no
// <h1> to name it. Fix the page, don't work around the tool.
//
// Re-run whenever a verification tab is added, deleted or re-summarised - see
// the regenerate table in CLAUDE.md.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const WIKI = join(dirname(fileURLToPath(import.meta.url)), "..");
const PAGE = join(WIKI, "verification.html");
const BEGIN = "<!-- BEGIN generated by wiki/tools/bake-verification-index.mjs - do not edit between the markers -->";
const END = "<!-- END generated -->";

const problems = [];

/** The verification panel of one page, or null. Panels are top-level in
 *  article.doc and never nested, so the next </section> closes this one. */
function panel(html) {
    const open = html.indexOf('data-tab="verification"');
    if (open < 0) { return null; }
    const start = html.lastIndexOf("<section", open);
    const end = html.indexOf("</section>", open);
    if (start < 0 || end < 0) { return null; }
    return html.slice(start, end);
}

function text(html) {
    return html.replace(/<[^>]+>/g, "")
        .replace(/&mdash;/g, "-").replace(/&nbsp;/g, " ")
        .replace(/\s+/g, " ").trim();
}

/** Sort key: alphabetical on the page's own title, ignoring a leading article,
 *  so "The horse dimension" files under H where a reader looks for it. */
function key(title) {
    return title.toLowerCase().replace(/^(the|a|an)\s+/, "");
}

const rows = [];

for (const file of readdirSync(WIKI).filter((f) => f.endsWith(".html")).sort()) {
    if (file === "verification.html") { continue; }
    const html = readFileSync(join(WIKI, file), "utf8");

    const summaries = html.match(/<div class="note verify-summary">[\s\S]*?<\/div>/g) || [];
    const body = panel(html);

    if (!body) {
        if (summaries.length) {
            problems.push(`${file}: has a verify-summary box but no verification tab`);
        }
        continue;
    }
    const inside = body.match(/<div class="note verify-summary">[\s\S]*?<\/div>/g) || [];
    if (inside.length !== 1 || summaries.length !== inside.length) {
        problems.push(`${file}: a verification tab needs exactly one verify-summary box `
            + `inside it (found ${inside.length} inside, ${summaries.length} on the page)`);
        continue;
    }
    const sentence = (inside[0].match(/<p>([\s\S]*?)<\/p>/) || [])[1];
    if (!sentence || !text(sentence)) {
        problems.push(`${file}: the verify-summary box has no sentence in a <p>`);
        continue;
    }
    const h1 = (html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/) || [])[1];
    if (!h1) {
        problems.push(`${file}: no <h1> to name the row`);
        continue;
    }
    rows.push({
        file,
        title: text(h1),
        sentence: sentence.replace(/\s+/g, " ").trim(),
        checks: (body.match(/<li[\s>]/g) || []).length
    });
}

if (problems.length) {
    console.error("bake-verification-index: refusing to write a wrong index.\n");
    for (const p of problems) { console.error("  " + p); }
    process.exit(1);
}

rows.sort((a, b) => key(a.title).localeCompare(key(b.title)));

const out = [BEGIN];
out.push(`<p class="verify-count">`);
out.push(`    <strong>${rows.length}</strong> ${rows.length === 1 ? "page has" : "pages have"} `
    + `something built and not yet confirmed, `
    + `<strong>${rows.reduce((n, r) => n + r.checks, 0)}</strong> checks `
    + `${rows.length === 1 ? "on it" : "between them"}.`);
out.push(`</p>`);
out.push(`<ul class="verify-index">`);
for (const r of rows) {
    out.push(`    <li>`);
    out.push(`        <a href="${r.file}#verification">${r.title}</a>`);
    out.push(`        <span class="verify-checks">${r.checks} check${r.checks === 1 ? "" : "s"}</span>`);
    out.push(`        <span class="verify-what">${r.sentence}</span>`);
    out.push(`    </li>`);
}
out.push(`</ul>`);
out.push(END);

const page = readFileSync(PAGE, "utf8");
const a = page.indexOf(BEGIN);
const b = page.indexOf(END);
if (a < 0 || b < 0) {
    console.error(`bake-verification-index: ${PAGE} has no BEGIN/END generated markers.`);
    process.exit(1);
}
writeFileSync(PAGE, page.slice(0, a) + out.join("\n") + page.slice(b + END.length));

console.log(`bake-verification-index: ${rows.length} pages, `
    + `${rows.reduce((n, r) => n + r.checks, 0)} checks.`);
