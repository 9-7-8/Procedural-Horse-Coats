/*
 * Bakes wiki/behaviour-hierarchy.html: every AI goal a horse runs, vanilla's and
 * this mod's, stacked by priority, with the flags each one claims and where two
 * goals at one priority fight over the same flag.
 *
 * WHY A BAKE. A hand-written list of goal priorities is a derived number, and the
 * repo has learned what those do (known-gaps #13): the list is right the day it is
 * written and wrong the first time somebody adds a goal. So this reads the
 * registrations out of the source instead:
 *
 *   - this mod's: every `goalSelector.addGoal(<priority>, new <Goal>(` under
 *     neoforge-26.1.2/src/main/java, with the priority expression resolved against
 *     the `static final int` constants it names, the flags read off the goal
 *     class's own setFlags call, and the first sentence of its javadoc;
 *   - vanilla's: AbstractHorse.registerGoals / addBehaviourGoals out of the patched
 *     sources jar the build already has, with each goal's flags read the same way.
 *
 *     node wiki/tools/bake-behaviour-hierarchy.mjs
 *
 * Run it after adding, removing or re-prioritising any goal. Needs the moddev
 * sources jar, so run :neoforge-26.1.2:compileJava once on a fresh clone first.
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, dirname, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const ROOT = dirname(dirname(dirname(fileURLToPath(import.meta.url))));
const SRC = join(ROOT, "neoforge-26.1.2", "src", "main", "java");
const JAR = join(ROOT, "neoforge-26.1.2", "build", "moddev", "artifacts",
    "minecraft-patched-26.1.2.100-sources.jar");
const PAGE = join(ROOT, "wiki", "behaviour-hierarchy.html");
const BEGIN = "<!-- BEGIN generated by wiki/tools/bake-behaviour-hierarchy.mjs - do not edit between the markers -->";
const END = "<!-- END generated -->";

// ---- reading source ---------------------------------------------------------

function walk(dir, out = []) {
    for (const name of readdirSync(dir)) {
        const p = join(dir, name);
        if (statSync(p).isDirectory()) walk(p, out);
        else if (name.endsWith(".java")) out.push(p);
    }
    return out;
}

const files = walk(SRC).map((path) => ({ path, text: readFileSync(path, "utf8") }));

function vanillaSource(path) {
    if (!existsSync(JAR)) {
        throw new Error("no sources jar at " + JAR + " - run ./gradlew :neoforge-26.1.2:compileJava first");
    }
    try {
        return execFileSync("unzip", ["-p", JAR, path], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
    } catch (e) {
        return "";
    }
}

/** `static final int NAME = 3;` everywhere, keyed "Class.NAME" and, per file, "NAME". */
const constants = new Map();
for (const f of files) {
    const cls = f.path.split(sep).pop().replace(".java", "");
    for (const m of f.text.matchAll(/static\s+final\s+int\s+(\w+)\s*=\s*(-?\d+)\s*;/g)) {
        constants.set(cls + "." + m[1], Number(m[2]));
        constants.set(f.path + "#" + m[1], Number(m[2]));
    }
}

function resolvePriority(expr, file) {
    const e = expr.trim();
    if (/^-?\d+$/.test(e)) return { value: Number(e) };
    if (/\.getPriority\(\)$/.test(e)) return { value: null, inherits: true };
    const m = /^([\w.]+)\s*(?:([+-])\s*(\d+))?$/.exec(e);
    if (!m) return { value: null };
    const name = m[1];
    const base = name.includes(".") ? constants.get(name) : constants.get(file + "#" + name);
    if (base === undefined) return { value: null };
    const delta = m[2] ? (m[2] === "+" ? 1 : -1) * Number(m[3]) : 0;
    return { value: base + delta };
}

/** The source of one class - a top-level class, or a nested `static final class`. */
function classSegment(text, name) {
    const decl = new RegExp("(?:public\\s+)?(?:static\\s+)?(?:final\\s+)?class\\s+" + name + "\\b[^{]*\\{");
    const m = decl.exec(text);
    if (!m) return null;
    const start = m.index;
    const rest = text.slice(start + m[0].length);
    const next = /\n\s*(?:public\s+|private\s+)?static\s+final\s+class\s+\w+/.exec(rest);
    const body = next ? rest.slice(0, next.index) : rest;
    // the javadoc immediately above the declaration
    const before = text.slice(0, start);
    const jd = /\/\*\*([\s\S]*?)\*\/\s*$/.exec(before);
    return { header: m[0], body, javadoc: jd ? jd[1] : "" };
}

function flagsOf(segment) {
    if (!segment) return [];
    const m = /setFlags\(\s*EnumSet\.of\(([^)]*)\)\s*\)/.exec(segment.body);
    if (!m) return [];
    return m[1].split(",").map((s) => s.trim().replace(/^(Goal\.)?Flag\./, "")).filter(Boolean);
}

function superOf(segment) {
    const m = segment && /extends\s+([\w.]+)/.exec(segment.header);
    return m ? m[1].split(".").pop() : null;
}

function firstSentence(javadoc) {
    const text = javadoc
        .split("\n").map((l) => l.replace(/^\s*\*\s?/, "")).join(" ")
        .replace(/\{@(?:link|code|value)\s+(?:[\w.]*#)?([^}]+)\}/g, "$1")
        .replace(/<[^>]+>/g, "")
        .replace(/\s+/g, " ")
        .trim();
    const paragraph = text.split(/\s@\w+/)[0];
    const m = /^(.+?[.!?])(\s|$)/.exec(paragraph);
    return (m ? m[1] : paragraph).trim();
}

// ---- vanilla ----------------------------------------------------------------

const VANILLA_WORDS = {
    FloatGoal: "Keeps its head above water.",
    RunAroundLikeCrazyGoal: "An untamed horse bucks and bolts with a rider on it - how taming works.",
    BreedGoal: "Walks to a mate while in love mode.",
    TemptGoal: "Follows a player holding a golden carrot or apple.",
    FollowParentGoal: "A foal keeps near an adult of its kind.",
    WaterAvoidingRandomStrollGoal: "Wanders.",
    LookAtPlayerGoal: "Looks at a player nearby.",
    RandomLookAroundGoal: "Glances about.",
    RandomStandGoal: "Rears up now and then.",
    MountPanicGoal: "Bolts when hurt.",
};

/** Vanilla goals that do not live in ai/goal. None today; kept so the next one is a line. */
const VANILLA_PATHS = {};

const vanillaFlagCache = new Map();
function vanillaFlags(name, depth = 0) {
    if (vanillaFlagCache.has(name)) return vanillaFlagCache.get(name);
    const path = VANILLA_PATHS[name] || "net/minecraft/world/entity/ai/goal/" + name + ".java";
    const seg = classSegment(vanillaSource(path), name);
    let flags = flagsOf(seg);
    if (!flags.length && depth < 3) {
        const parent = superOf(seg);
        if (parent && parent !== "Goal") flags = vanillaFlags(parent, depth + 1);
    }
    vanillaFlagCache.set(name, flags);
    return flags;
}

const abstractHorse = vanillaSource("net/minecraft/world/entity/animal/equine/AbstractHorse.java");
const vanilla = [];
for (const m of abstractHorse.matchAll(/this\.goalSelector\.addGoal\((\d+),\s*new\s+([\w.]+)\(/g)) {
    const cls = m[2].split(".").pop();
    let flags;
    if (cls === "MountPanicGoal") {
        flags = vanillaFlags("PanicGoal");
    } else {
        flags = vanillaFlags(cls);
    }
    vanilla.push({ priority: Number(m[1]), name: cls, flags, words: VANILLA_WORDS[cls] || "",
        where: "vanilla AbstractHorse", kind: "vanilla", selector: "goal" });
}

// ---- this mod ---------------------------------------------------------------

const ALSO_SKIP = /[\\/]entity[\\/]/;     // the cowboy's own goals are not a horse's
const goalClasses = new Map();
for (const f of files) {
    for (const m of f.text.matchAll(/class\s+(\w+)\s+extends\s+(\w*Goal)\b/g)) {
        goalClasses.set(m[1], { file: f, superName: m[2] });
    }
}

const mod = [];
let replaces = null;
for (const f of files) {
    if (ALSO_SKIP.test(f.path)) continue;
    for (const m of f.text.matchAll(/(goalSelector|targetSelector)\.addGoal\(\s*([^,]+?)\s*,\s*new\s+([\w.]+)\s*\(/g)) {
        const cls = m[3].split(".").pop();
        const p = resolvePriority(m[2], f.path);
        const info = goalClasses.get(cls);
        const seg = info ? classSegment(info.file.text, cls) : null;
        let flags = flagsOf(seg);
        if (!flags.length && info && info.superName !== "Goal") flags = vanillaFlags(info.superName);
        const handler = relative(join(SRC, "com", "example", "horsegenetics", "neoforge"), f.path)
            .replace(/\\/g, "/").replace(".java", "");
        let who = "every horse";
        let onHorse = true;
        if (/Lycanthropy/.test(f.path)) {
            who = "a shifted lycan's animal, not a horse";
            onHorse = false;    // a different mob's selector - it cannot conflict with a horse's goals
        } else if (/CowboyHandler/.test(f.path)) {
            who = "horses in a cowboy's string";
        }
        const entry = {
            priority: p.value, name: cls, flags, words: seg ? firstSentence(seg.javadoc) : "",
            where: handler + " · " + who, kind: "mod",
            selector: m[1] === "targetSelector" ? "target" : "goal",
            onHorse,
        };
        if (p.inherits) {
            // HorsePanicGoal takes the slot of the vanilla panic it removes.
            const panic = vanilla.find((v) => v.name === "MountPanicGoal");
            entry.priority = panic ? panic.priority : 1;
            entry.replaces = "MountPanicGoal";
            replaces = entry;
        }
        if (entry.priority === null) {
            console.warn("could not resolve priority '" + m[2] + "' for " + cls + " in " + handler);
            continue;
        }
        mod.push(entry);
    }
}
if (replaces) {
    for (const v of vanilla) if (v.name === replaces.replaces) v.kind = "replaced";
}

// ---- render -----------------------------------------------------------------

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function conflicts(goals) {
    const live = goals.filter((g) => g.kind !== "replaced");
    const out = [];
    for (let i = 0; i < live.length; i++) {
        for (let j = i + 1; j < live.length; j++) {
            const shared = live[i].flags.filter((fl) => live[j].flags.includes(fl) && fl !== "TARGET");
            if (shared.length) out.push([live[i].name, live[j].name, shared]);
        }
    }
    return out;
}

function renderSelector(all, selector, title, lede) {
    const goals = all.filter((g) => g.selector === selector);
    const byPriority = new Map();
    for (const g of goals) {
        if (!byPriority.has(g.priority)) byPriority.set(g.priority, []);
        byPriority.get(g.priority).push(g);
    }
    const priorities = [...byPriority.keys()].sort((a, b) => a - b);
    let html = `<h2 class="bh-selector" id="${selector}-selector">${esc(title)}</h2>\n<p class="bh-lede">${lede}</p>\n`;
    html += `<div class="bh-rail">\n`;
    for (const p of priorities) {
        const level = byPriority.get(p).sort((a, b) =>
            (a.kind === "vanilla" || a.kind === "replaced" ? 0 : 1) - (b.kind === "vanilla" || b.kind === "replaced" ? 0 : 1)
            || a.name.localeCompare(b.name));
        const live = level.filter((g) => g.kind !== "replaced").length;
        html += `<section class="bh-level" id="${selector}-p${p}">\n`;
        html += `  <h3 class="bh-priority">Priority ${p}<span class="bh-count">${live} goal${live === 1 ? "" : "s"}</span></h3>\n`;
        html += `  <ul class="bh-goals">\n`;
        for (const g of level) {
            const flags = g.flags.length
                ? g.flags.map((fl) => `<span class="bh-flag bh-flag-${fl.toLowerCase()}">${esc(fl)}</span>`).join("")
                : `<span class="bh-flag bh-flag-none">no flags</span>`;
            const tag = g.kind === "mod" ? "this mod" : g.kind === "replaced" ? "vanilla, replaced" : "vanilla";
            html += `    <li class="bh-goal bh-${g.kind}">\n`;
            html += `      <div class="bh-head"><code>${esc(g.name)}</code><span class="bh-tag">${tag}</span>${flags}</div>\n`;
            if (g.words) html += `      <p class="bh-words">${esc(g.words)}</p>\n`;
            if (g.replaces) html += `      <p class="bh-words">Takes the place of vanilla's <code>${esc(g.replaces)}</code>, which is removed.</p>\n`;
            html += `      <p class="bh-where">${esc(g.where)}</p>\n`;
            html += `    </li>\n`;
        }
        html += `  </ul>\n`;
        for (const [a, b, shared] of conflicts(level)) {
            html += `  <p class="bh-conflict"><strong>${esc(a)}</strong> and <strong>${esc(b)}</strong> both claim ${shared.map((s) => `<code>${s}</code>`).join(" and ")} at the same priority: neither can interrupt the other, so whichever started first keeps it.</p>\n`;
        }
        html += `</section>\n`;
    }
    html += `</div>\n`;
    return html;
}

const horseMod = mod.filter((g) => g.onHorse);
const elsewhere = mod.filter((g) => !g.onHorse);
const all = [...vanilla, ...horseMod];
const modCount = horseMod.filter((g) => g.selector === "goal").length;
const vanillaCount = vanilla.filter((g) => g.kind === "vanilla").length;
const targetCount = horseMod.filter((g) => g.selector === "target").length;
let body = `<p class="bh-summary">${modCount + vanillaCount} goals on a horse &mdash; ${vanillaCount} vanilla, ${modCount} from this mod &mdash; and ${targetCount} targeting goal${targetCount === 1 ? "" : "s"}.</p>\n`;
body += renderSelector(all, "goal", "The goal selector",
    "What a horse is <em>doing</em>: moving, looking, jumping. Lower numbers first.");
body += renderSelector(all, "target", "The target selector",
    "What a horse is <em>angry at</em>. Separate from the goals above: a target is chosen here and acted on there.");
if (elsewhere.length) {
    body += `<h2 class="bh-selector" id="not-a-horse">Added to something that is not a horse</h2>\n<ul>\n`;
    for (const g of elsewhere) {
        body += `  <li><code>${esc(g.name)}</code> at priority ${g.priority} &mdash; ${esc(g.words)} <span class="bh-where">${esc(g.where)}</span></li>\n`;
    }
    body += `</ul>\n`;
}

const page = readFileSync(PAGE, "utf8");
const a = page.indexOf(BEGIN);
const b = page.indexOf(END);
if (a < 0 || b < 0) throw new Error("markers not found in " + PAGE);
writeFileSync(PAGE, page.slice(0, a + BEGIN.length) + "\n" + body + page.slice(b));
console.log(`behaviour hierarchy: ${vanillaCount} vanilla + ${modCount} mod goals, ${mod.filter((g) => g.selector === "target").length} target -> wiki/behaviour-hierarchy.html`);
