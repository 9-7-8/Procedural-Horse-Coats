#!/usr/bin/env node
/*
 * Bakes wiki/text/ - the corpus a coding agent should search instead of the
 * wiki's .html: plain prose with the markup stripped, one file per page (or
 * per tab, for a page that has gameplay/coding/science panels), plus a flat
 * anchor index (wiki/text/index.txt) mapping heading -> file#anchor so an
 * agent can jump straight to a section instead of reading a whole page.
 *
 * WHAT IS LEFT OUT, ON PURPOSE:
 *   - session-log.html is only an index; its individual records live directly
 *     under session-log/. releases.html is likewise chronicle material.
 *   - Any page that is wholly generated (has a "BEGIN generated by" marker
 *     covering effectively the whole page: verification.html, roadmap.html,
 *     gene-census.html, timeline-of-genes.html, behaviour-hierarchy.html) -
 *     it is a derived table, not something to read prose out of.
 *   - making-a-gene.html: pending an audit, left out for now.
 *
 * THIS IS A BAKE, LIKE EVERY OTHER ONE HERE. It fails silently if stale, so
 * re-run it whenever wiki text changes (same trigger as build-search-index.mjs):
 *
 *     node wiki/tools/bake-agent-text.mjs
 *     node wiki/tools/bake-agent-text.mjs --check   # fails if checked-in output is stale
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync, existsSync } from "node:fs";
import { join } from "node:path";
import { WIKI, htmlFiles, text, panels, headings, frontMatter, articleBody } from "./wiki-parse.mjs";

const OUT_DIR = join(WIKI, "text");
const CHECK = process.argv.includes("--check");

/** Chronicle indexes: append-only history is not reference prose. */
const EXCLUDE_CHRONICLE = new Set(["session-log.html", "releases.html"]);

/** Whole pages that are generated tables/indices, not hand-authored prose. */
const EXCLUDE_GENERATED = new Set([
    "verification.html", "roadmap.html", "gene-census.html",
    "timeline-of-genes.html", "behaviour-hierarchy.html"
]);

/** Pending their own audit - left out until then. */
const EXCLUDE_DEFERRED = new Set(["making-a-gene.html"]);

const TABS = ["gameplay", "coding", "science"];

function stem(href) {
    // "wiki/gene-agouti.html" -> "gene-agouti"; "index.html" -> "index".
    return href.replace(/^wiki\//, "").replace(/\.html$/, "");
}

const files = {}; // relative filename -> text content
const anchorLines = [];

for (const file of htmlFiles()) {
    const name = file.href.replace(/^wiki\//, "");
    if (EXCLUDE_CHRONICLE.has(name) || EXCLUDE_GENERATED.has(name) || EXCLUDE_DEFERRED.has(name)) continue;

    const raw = readFileSync(file.path, "utf8");
    const { title, eyebrow, lede } = frontMatter(raw);
    const body = articleBody(raw);
    const split = panels(body);
    const realTabs = TABS.filter((t) => split[t] && text(split[t]));
    const header = [title, eyebrow ? `(${eyebrow})` : "", lede].filter(Boolean).join("\n");
    const base = stem(file.href);

    function emit(suffix, tabLabel, html) {
        const body = text(html);
        if (!body) return;
        files[`${base}${suffix}.txt`] = `${header}\n\n${body}\n`;
        for (const h of headings(html)) {
            if (!h.id) continue;
            anchorLines.push(`${file.href}#${h.id}\t${tabLabel}\t${h.title}`);
        }
    }

    if (realTabs.length === 0) {
        emit("", "all", split.all);
    } else {
        // "all" on a tabbed page is header material (already captured above);
        // only worth a file of its own if there is real shared prose in it.
        const allBody = text(split.all);
        if (allBody && allBody !== text(header)) emit(".all", "all", split.all);
        for (const tab of realTabs) emit(`.${tab}`, tab, split[tab]);
    }
}

const indexLines = anchorLines.sort();
files["index.txt"] = indexLines.join("\n") + "\n";

if (CHECK) {
    const existing = existsSync(OUT_DIR) ? new Set(readdirSync(OUT_DIR)) : new Set();
    const wanted = new Set(Object.keys(files));
    let stale = false;
    for (const name of wanted) {
        const path = join(OUT_DIR, name);
        if (!existsSync(path) || readFileSync(path, "utf8") !== files[name]) {
            console.log(`stale or missing: wiki/text/${name}`);
            stale = true;
        }
    }
    for (const name of existing) {
        if (!wanted.has(name)) {
            console.log(`orphaned (no longer baked): wiki/text/${name}`);
            stale = true;
        }
    }
    if (stale) {
        console.log("\nwiki/text/ is stale - run: node wiki/tools/bake-agent-text.mjs");
        process.exit(1);
    }
    console.log(`wiki/text/ is fresh (${wanted.size} files)`);
    process.exit(0);
}

rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });
for (const [name, content] of Object.entries(files)) {
    writeFileSync(join(OUT_DIR, name), content);
}
const words = Object.values(files).reduce((n, c) => n + c.split(/\s+/).length, 0);
console.log(`baked ${Object.keys(files).length} files, ${words.toLocaleString()} words -> wiki/text/`);
