#!/usr/bin/env node
// Writes the gene list of wiki/timeline-of-genes.html: every gene that has a
// page, grouped by the commit that added it, newest first.
//
//   node wiki/tools/bake-gene-timeline.mjs
//
// Two sources, both derived, neither typed:
//
//   * WHICH genes, and what they are called - the generated span of
//     wiki/pages.js, which :common:bakeGeneWikiPages writes from the registry.
//     So a parked gene (absent from genes/index.json) is absent here too, and a
//     gene's label is its page's own <h1>.
//   * WHEN - git. One pass over the history of the source (*.java, *.json,
//     outside wiki/), and a gene's batch is the first commit that ADDS a line
//     containing its key literal, "horsegenetics.<slug>". That is the moment
//     the gene existed in code, whatever the file was called then.
//
// Its one known blind spot: a gene whose key was renamed shows up at the
// rename, not at its birth. A gene whose key never appears as a literal (a
// key built by concatenation) lands in "Undated" at the bottom, and is named
// on stdout so it can be looked at.
//
// Re-run after :common:bakeGeneWikiPages, in the same change - see the
// regenerate table in CLAUDE.md.

import { spawn } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const WIKI = join(dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = join(WIKI, "..");
const PAGE = join(WIKI, "timeline-of-genes.html");
const BEGIN = "<!-- BEGIN generated by wiki/tools/bake-gene-timeline.mjs - do not edit between the markers -->";
const END = "<!-- END generated -->";

// ---- the genes, from pages.js ----------------------------------------------

function genesFromPages() {
    const src = readFileSync(join(WIKI, "pages.js"), "utf8");
    const from = src.indexOf("BEGIN generated");
    const to = src.indexOf("END generated", from);
    if (from < 0 || to < 0) {
        throw new Error("pages.js: no generated span - run :common:bakeGeneWikiPages first");
    }
    const span = src.slice(from, to);
    const genes = [];
    // Line by line, so each gene keeps the family label of the section above it.
    // (Not one regex per section: every item carries its own views: [...] list,
    // and a lazy match to the section's closing bracket stops at the first.)
    const titleRe = /title:\s*"((?:[^"\\]|\\.)*)"/;
    const itemRe = /href:\s*"(gene-[^"]+\.html)",\s*text:\s*"((?:[^"\\]|\\.)*)",\s*kind:\s*"(\w+)"/;
    let family = "";
    for (const line of span.split(/\r?\n/)) {
        const t = titleRe.exec(line);
        if (t) {
            family = JSON.parse(`"${t[1]}"`);
            continue;
        }
        const it = itemRe.exec(line);
        if (it) {
            const href = it[1];
            const slug = href.replace(/^gene-/, "").replace(/\.html$/, "").replace(/-/g, "_");
            genes.push({ href, slug, name: JSON.parse(`"${it[2]}"`), kind: it[3], family });
        }
    }
    if (genes.length === 0) {
        throw new Error("pages.js: the generated span lists no gene pages");
    }
    return genes;
}

// ---- when each key first appeared, from git ---------------------------------

function firstSeen(wanted) {
    return new Promise((resolve, reject) => {
        const git = spawn("git", [
            "log", "--reverse", "--no-color", "-p", "-U0", "--date=short",
            "--format=@@COMMIT %H %ad %s",
            "--", "*.java", "*.json", ":(exclude)wiki/**", ":(exclude)index.html",
        ], { cwd: ROOT });
        const seen = new Map();   // slug -> commit
        const commits = [];       // in history order
        let current = null;
        let buffer = "";
        const keyRe = /"horsegenetics\.([a-z0-9_]+)"/g;
        const take = (line) => {
            if (line.startsWith("@@COMMIT ")) {
                const m = /^@@COMMIT (\w+) (\S+) (.*)$/.exec(line);
                current = { hash: m[1], date: m[2], subject: m[3], index: commits.length };
                commits.push(current);
                return;
            }
            if (!current || !line.startsWith("+") || line.startsWith("+++")) {
                return;
            }
            for (const k of line.matchAll(keyRe)) {
                if (wanted.has(k[1]) && !seen.has(k[1])) {
                    seen.set(k[1], current);
                }
            }
        };
        git.stdout.setEncoding("utf8");
        git.stdout.on("data", (chunk) => {
            buffer += chunk;
            let nl;
            while ((nl = buffer.indexOf("\n")) >= 0) {
                take(buffer.slice(0, nl));
                buffer = buffer.slice(nl + 1);
            }
        });
        let err = "";
        git.stderr.on("data", (d) => { err += d; });
        git.on("close", (code) => {
            if (buffer) take(buffer);
            if (code !== 0) reject(new Error("git log failed: " + err));
            else resolve(seen);
        });
    });
}

// ---- the HTML ---------------------------------------------------------------

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const MONTHS = ["January", "February", "March", "April", "May", "June", "July",
    "August", "September", "October", "November", "December"];
function longDate(iso) {
    const [y, m, d] = iso.split("-").map(Number);
    return `${d} ${MONTHS[m - 1]} ${y}`;
}

function geneItem(g) {
    const icon = existsSync(join(WIKI, "assets", "gene-icons", `${g.slug}.png`))
        ? `<img src="assets/gene-icons/${g.slug}.png" alt="" width="72" loading="lazy">`
        : `<span class="tl-noicon" title="changes no pixel of the coat, so it has no icon">&ndash;</span>`;
    return `            <li class="tl-${g.kind === "natural" ? "natural" : "magical"}">`
        + `<a href="${esc(g.href)}" title="${esc(g.family)}">${icon}<span>${esc(g.name)}</span></a></li>`;
}

function render(genes, seen) {
    // commit hash -> { commit, genes }
    const batches = new Map();
    const undated = [];
    for (const g of genes) {
        const c = seen.get(g.slug);
        if (!c) {
            undated.push(g);
            continue;
        }
        if (!batches.has(c.hash)) batches.set(c.hash, { commit: c, genes: [] });
        batches.get(c.hash).genes.push(g);
    }
    // newest commit first; then by day
    const ordered = [...batches.values()].sort((a, b) => b.commit.index - a.commit.index);
    const days = new Map();
    for (const b of ordered) {
        if (!days.has(b.commit.date)) days.set(b.commit.date, []);
        days.get(b.commit.date).push(b);
    }
    const byName = (a, b) => a.name.localeCompare(b.name, "en", { sensitivity: "base" });
    const out = [];
    out.push(`<p class="tl-summary">${genes.length} genes with pages, in ${ordered.length} batches over ${days.size} days.</p>`);
    for (const [date, list] of days) {
        const count = list.reduce((n, b) => n + b.genes.length, 0);
        out.push(`<section class="tl-day">`);
        out.push(`    <h2 id="d${date}" class="tl-date">${longDate(date)} <span class="tl-count">${count} gene${count === 1 ? "" : "s"}</span></h2>`);
        for (const b of list) {
            out.push(`    <div class="tl-batch">`);
            out.push(`        <p class="tl-batch-title"><code>${b.commit.hash.slice(0, 7)}</code> ${esc(b.commit.subject)}</p>`);
            out.push(`        <ul class="tl-genes">`);
            for (const g of b.genes.sort(byName)) out.push(geneItem(g));
            out.push(`        </ul>`);
            out.push(`    </div>`);
        }
        out.push(`</section>`);
    }
    if (undated.length) {
        out.push(`<section class="tl-day">`);
        out.push(`    <h2 id="undated" class="tl-date">Undated <span class="tl-count">${undated.length}</span></h2>`);
        out.push(`    <div class="tl-batch">`);
        out.push(`        <p class="tl-batch-title">No commit ever added a line with the key as a literal - built by concatenation, most likely.</p>`);
        out.push(`        <ul class="tl-genes">`);
        for (const g of undated.sort(byName)) out.push(geneItem(g));
        out.push(`        </ul>`);
        out.push(`    </div>`);
        out.push(`</section>`);
    }
    return { html: out.join("\n"), batches: ordered.length, undated };
}

// ---- main -------------------------------------------------------------------

const genes = genesFromPages();
const seen = await firstSeen(new Set(genes.map((g) => g.slug)));
const { html, batches, undated } = render(genes, seen);

const page = readFileSync(PAGE, "utf8");
const a = page.indexOf(BEGIN);
const b = page.indexOf(END, a);
if (a < 0 || b < 0) {
    throw new Error("timeline-of-genes.html: generated markers not found");
}
const nl = page.includes("\r\n") ? "\r\n" : "\n";
const next = page.slice(0, a + BEGIN.length) + nl + html.replace(/\n/g, nl) + nl + page.slice(b);
if (next !== page) {
    writeFileSync(PAGE, next);
}
console.log(`timeline: ${genes.length} genes in ${batches} batches`
    + (undated.length ? `; UNDATED: ${undated.map((g) => g.slug).join(", ")}` : ""));
