#!/usr/bin/env node
// Writes the index of wiki/roadmap.html: one row per wiki page that carries a
// Roadmap tab, alphabetical, with that tab's own one-sentence summary.
//
//   node wiki/tools/bake-roadmap-index.mjs
//
// The twin of bake-verification-index.mjs, and deliberately the same shape,
// because the two lists failed the same way. Nothing here is typed. A subject
// is on this list BY HAVING A ROADMAP TAB, the same way a gene is on the census
// by existing. The contract a page must keep, and which this tool enforces:
//
//   <section id="roadmap" class="tab-panel" data-tab="roadmap"
//            data-tab-label="Roadmap"
//            data-tab-hint="Planned, not built">
//
//   <div class="note roadmap-summary">
//       <span class="label">What is still planned here</span>
//       <p>One sentence saying what is planned and unbuilt.</p>
//   </div>
//
// The sentence is the row. The count beside it is the panel's own <h2>/<h3>
// tally - one per plan - computed here rather than written down, so a list that
// shrinks as things ship says so without anybody editing this page.
//
// It HARD-FAILS rather than writing a wrong index, because a roadmap that
// quietly omits a subject is how the old page rotted: a panel with no summary
// box, a summary box outside a roadmap panel, two of either, or a page with no
// <h1> to name it. Fix the page, don't work around the tool.
//
// Re-run whenever a roadmap tab is added, deleted or re-summarised - see the
// regenerate table in CLAUDE.md.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const WIKI = join(dirname(fileURLToPath(import.meta.url)), "..");
const PAGE = join(WIKI, "roadmap.html");
const BEGIN = "<!-- BEGIN generated by wiki/tools/bake-roadmap-index.mjs - do not edit between the markers -->";
const END = "<!-- END generated -->";

const problems = [];

/** The roadmap panel of one page, or null. Panels are top-level in article.doc
 *  and never nested, so the next </section> closes this one. */
function panel(html) {
    const open = html.indexOf('data-tab="roadmap"');
    if (open < 0) { return null; }
    const start = html.lastIndexOf("<section", open);
    const end = html.indexOf("</section>", open);
    if (start < 0 || end < 0) { return null; }
    return html.slice(start, end);
}

function text(html) {
    return html.replace(/<[^>]+>/g, "")
        .replace(/&mdash;/g, "-").replace(/&nbsp;/g, " ")
        .replace(/\s+/g, " ").trim();
}

/** Sort key: alphabetical on the page's own title, ignoring a leading article,
 *  so "The horse browser" files under H where a reader looks for it. */
function key(title) {
    return title.toLowerCase().replace(/^(the|a|an)\s+/, "");
}

const rows = [];

for (const file of readdirSync(WIKI).filter((f) => f.endsWith(".html")).sort()) {
    if (file === "roadmap.html") { continue; }
    const html = readFileSync(join(WIKI, file), "utf8");

    const summaries = html.match(/<div class="note roadmap-summary">[\s\S]*?<\/div>/g) || [];
    const body = panel(html);

    if (!body) {
        if (summaries.length) {
            problems.push(`${file}: has a roadmap-summary box but no roadmap tab`);
        }
        continue;
    }
    const inside = body.match(/<div class="note roadmap-summary">[\s\S]*?<\/div>/g) || [];
    if (inside.length !== 1 || summaries.length !== inside.length) {
        problems.push(`${file}: a roadmap tab needs exactly one roadmap-summary box `
            + `inside it (found ${inside.length} inside, ${summaries.length} on the page)`);
        continue;
    }
    const sentence = (inside[0].match(/<p>([\s\S]*?)<\/p>/) || [])[1];
    if (!sentence || !text(sentence)) {
        problems.push(`${file}: the roadmap-summary box has no sentence in a <p>`);
        continue;
    }
    const h1 = (html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/) || [])[1];
    if (!h1) {
        problems.push(`${file}: no <h1> to name the row`);
        continue;
    }
    rows.push({
        file,
        title: text(h1),
        sentence: sentence.replace(/\s+/g, " ").trim(),
        // One per heading in the panel. Floored at 1: a page whose single plan
        // is the page - its heading dissolved into the <h1> because repeating
        // the title under it read badly - still carries one plan, and "0
        // entries" beside a row that exists is just wrong.
        plans: Math.max(1, (body.match(/<h[23][\s>]/g) || []).length)
    });
}

if (problems.length) {
    console.error("bake-roadmap-index: refusing to write a wrong index.\n");
    for (const p of problems) { console.error("  " + p); }
    process.exit(1);
}

rows.sort((a, b) => key(a.title).localeCompare(key(b.title)));

const total = rows.reduce((n, r) => n + r.plans, 0);

const out = [BEGIN];
out.push(`<p class="roadmap-count">`);
out.push(`    <strong>${rows.length}</strong> ${rows.length === 1 ? "page carries" : "pages carry"} `
    + `plans that are not built, `
    + `<strong>${total}</strong> ${total === 1 ? "entry" : "entries"} `
    + `${rows.length === 1 ? "on it" : "between them"}.`);
out.push(`</p>`);
out.push(`<ul class="roadmap-index">`);
for (const r of rows) {
    out.push(`    <li>`);
    out.push(`        <a href="${r.file}#roadmap">${r.title}</a>`);
    out.push(`        <span class="roadmap-plans">${r.plans} entr${r.plans === 1 ? "y" : "ies"}</span>`);
    out.push(`        <span class="roadmap-what">${r.sentence}</span>`);
    out.push(`    </li>`);
}
out.push(`</ul>`);
out.push(END);

const page = readFileSync(PAGE, "utf8");
const a = page.indexOf(BEGIN);
const b = page.indexOf(END);
if (a < 0 || b < 0) {
    console.error(`bake-roadmap-index: ${PAGE} has no BEGIN/END generated markers.`);
    process.exit(1);
}
writeFileSync(PAGE, page.slice(0, a) + out.join("\n") + page.slice(b + END.length));

console.log(`bake-roadmap-index: ${rows.length} pages, ${total} entries.`);
